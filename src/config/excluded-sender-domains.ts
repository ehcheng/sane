/**
 * Domains excluded from the sender picker during setup.
 *
 * These are personal email providers, commercial senders, financial
 * institutions, and other domains that are clearly not a school.
 *
 * To add domains: append to the appropriate section below.
 * The Set is built once at module load and used by gmail.fetchRecentSenders.
 * Duplicates are harmless — the Set dedupes automatically.
 */

/** TLD suffixes that are always excluded (e.g. all .gov domains). */
export const EXCLUDED_TLD_SUFFIXES: readonly string[] = [
  ".gov",
  ".mil",
];

/** Check whether a domain should be excluded (exact match OR TLD suffix). */
export function isDomainExcluded(domain: string): boolean {
  if (EXCLUDED_SENDER_DOMAINS.has(domain)) return true;
  if (EXCLUDED_TLD_SUFFIXES.some((suffix) => domain.endsWith(suffix))) return true;
  // Check parent domains — e.g. "email.schwab.com" matches "schwab.com"
  const parts = domain.split(".");
  for (let i = 1; i < parts.length - 1; i++) {
    if (EXCLUDED_SENDER_DOMAINS.has(parts.slice(i).join("."))) return true;
  }
  return false;
}

